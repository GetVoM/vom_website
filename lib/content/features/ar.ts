/** Arabic counting: 1, 2, 3–10 take their own forms; 11 and up take the accusative singular. */
function count(n: number, forms: { one: string; two: string; few: string; many: string }): string {
  if (n === 1) return forms.one;
  if (n === 2) return forms.two;
  return `${n} ${n <= 10 ? forms.few : forms.many}`;
}

